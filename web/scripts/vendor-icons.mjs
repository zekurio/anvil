// Regenerates src/ui/icon-data.ts from lucide-static (ISC). lucide-solid has no
// Solid 2 release, so the icons anvil uses are vendored as inline SVG markup.
//
// To add an icon: add its Lucide id to ICONS below, then run `npm run icons`.

import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = [
  // Node kinds. Each owns its icon; never reuse them for anything else.
  "file-input",
  "split",
  "film",
  "audio-lines",
  "captions",
  "package",
  "file-output",
  "square-terminal",
  // Navigation and objects.
  "library-big",
  "workflow",
  "list-video",
  "settings",
  "folder",
  "folder-open",
  "file-video",
  "hard-drive",
  "lock",
  // Actions.
  "play",
  "pause",
  "square",
  "x",
  "plus",
  "minus",
  "search",
  "check",
  "ban",
  "refresh-cw",
  "rotate-ccw",
  "trash-2",
  "copy",
  "pencil",
  "ellipsis",
  "grip-vertical",
  "maximize",
  "zoom-in",
  "zoom-out",
  "log-out",
  "external-link",
  "sun",
  "moon",
  // Direction.
  "chevron-down",
  "chevron-up",
  "chevron-left",
  "chevron-right",
  "arrow-left",
  "arrow-up-down",
  "corner-left-up",
  // State.
  "triangle-alert",
  "loader-circle",
  "circle-check",
  "circle-x",
  "circle-alert",
  "clock",
  "info",
  // Flow editor.
  "undo-2",
  "redo-2",
];

const require = createRequire(import.meta.url);
const packageDir = dirname(require.resolve("lucide-static/package.json"));
const iconsDir = resolve(packageDir, "icons");
const version = require("lucide-static/package.json").version;

const entries = ICONS.map((name) => {
  const svg = readFileSync(resolve(iconsDir, `${name}.svg`), "utf8");
  const body = svg
    .slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/\s*\n\s*/g, "")
    .replace(/ \/>/g, "/>");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
});

const out = `// Generated by scripts/vendor-icons.mjs from lucide-static v${version}. Do not edit.
//
// Icons by Lucide (https://lucide.dev), ISC License. The full notice is in
// icon-data.LICENSE beside this file.
//
// Each value is the inner markup of a 24x24 stroke icon.

export const ICON_DATA = {
${entries.join("\n")}
} as const;
`;

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../src/ui/icon-data.ts");
writeFileSync(target, out);
// The ISC licence asks for its notice to travel with every copy.
copyFileSync(resolve(packageDir, "LICENSE"), target.replace(/\.ts$/, ".LICENSE"));
console.log(`wrote ${ICONS.length} icons to ${target}`);
